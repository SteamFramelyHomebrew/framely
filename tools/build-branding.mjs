// Generate platform artwork from the approved SVGs. Commit these outputs so
// native/installer builds do not need Node.js or an image tool at build time.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {Resvg} from '@resvg/resvg-js';

const root = new URL('../', import.meta.url);
const branding = new URL('assets/branding/', root);
const app = await readFile(new URL('framely-app-icon.svg', branding));
const mark = await readFile(new URL('framely-mark.svg', branding), 'utf8');
await writeFile(new URL('framely-mark-light.svg', branding), mark.replace('color="#17191c"', 'color="#93c5ed"'));
const logo = await readFile(new URL('framely-logo.svg', branding), 'utf8');
await writeFile(new URL('framely-logo-light.svg', branding), logo.replace('color="#17191c"', 'color="#93c5ed"'));
const sizes = [16, 24, 32, 48, 64, 128, 256, 512, 1024];
const images = new Map();
await mkdir(new URL('icons/', branding), {recursive:true});
for (const size of sizes) {
  const png = new Resvg(app, {fitTo:{mode:'width', value:size}}).render().asPng();
  images.set(size, png);
  await writeFile(new URL(`icons/${size}.png`, branding), png);
}
await writeFile(new URL('framely-app-icon.png', branding), images.get(512));

// ICO entries contain PNG images, supported by the targeted Windows versions.
const icoSizes = sizes.filter(size => size <= 256);
const directory = Buffer.alloc(6 + 16 * icoSizes.length);
directory.writeUInt16LE(1, 2);
directory.writeUInt16LE(icoSizes.length, 4);
let offset = directory.length;
for (const [index, size] of icoSizes.entries()) {
  const entry = 6 + index * 16;
  directory[entry] = directory[entry + 1] = size === 256 ? 0 : size;
  directory.writeUInt16LE(1, entry + 4);
  directory.writeUInt16LE(32, entry + 6);
  directory.writeUInt32LE(images.get(size).length, entry + 8);
  directory.writeUInt32LE(offset, entry + 12);
  offset += images.get(size).length;
}
await writeFile(new URL('framely.ico', branding), Buffer.concat([directory, ...icoSizes.map(size => images.get(size))]));

// A small alpha mask is enough for the native pixel-art Dock renderer. This
// keeps the same SVG geometry without adding a runtime SVG/PNG dependency.
// Keep the body centered while the left tail extends beyond it. Expand the
// viewBox by 1 / 0.9 so the Dock glyph is 10% smaller than the standard mark.
const dockMark = mark.replace('viewBox="0 0 24 24"', 'viewBox="-1.333333 -1.333333 26.666666 26.666666"');
const rendered = new Resvg(dockMark, {fitTo:{mode:'width', value:48}}).render();
const mask = Array.from({length:48}, (_, y) => '  ' + Array.from({length:48}, (_, x) => rendered.pixels[(y * 48 + x) * 4 + 3]).join(',')).join(',\n');
await mkdir(new URL('native/', root), {recursive:true});
await writeFile(new URL('native/brand_mask.h', root), `// Generated by tools/build-branding.mjs from assets/branding/framely-mark.svg.\n#pragma once\nnamespace framely_brand {\ninline constexpr unsigned char mask[48 * 48] = {\n${mask}\n};\n}\n`);
console.log(`Generated platform icons and native mask from ${fileURLToPath(branding)}`);
